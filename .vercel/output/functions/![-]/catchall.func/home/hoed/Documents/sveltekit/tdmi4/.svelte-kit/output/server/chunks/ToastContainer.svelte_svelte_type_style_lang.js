const DEFAULT_DURATION = 5e3;
const DEFAULT_TYPE = "info";
const DEFAULT_SHOW_CLOSE_BUTTON = true;
const DEFAULT_PROGRESS = true;
const DEFAULT_PAUSE_ON_HOVER = true;
const MAX_TOASTS_DEFAULT = 5;
const storeConfig = {
  maxToasts: MAX_TOASTS_DEFAULT,
  defaultDuration: DEFAULT_DURATION
};
const { subscribe, update: updateStore } = writable([]);
const toastStore = {
  subscribe
  // You could expose a 'set' if absolutely necessary, but update is safer.
};
function generateId() {
  return crypto.randomUUID ? crypto.randomUUID() : `toast-${Math.random().toString(36).substring(2, 9)}-${Date.now()}`;
}
function getDefaultIcon(type) {
  let iconComponent;
  switch (type) {
    case "info":
      iconComponent = Info;
      break;
    case "success":
      iconComponent = Circle_check;
      break;
    case "warning":
      iconComponent = Triangle_alert;
      break;
    case "error":
      iconComponent = Circle_x;
      break;
    case "loading":
      iconComponent = Loader_circle;
      break;
    default:
      iconComponent = void 0;
      break;
  }
  return iconComponent;
}
function trimToasts() {
  updateStore((toasts) => {
    if (toasts.length > storeConfig.maxToasts) {
      return toasts.slice(0, storeConfig.maxToasts);
    }
    return toasts;
  });
}
function show(options) {
  const id = options.id || generateId();
  const type = options.type || DEFAULT_TYPE;
  const duration = options.duration === 0 ? Infinity : options.duration || storeConfig.defaultDuration;
  const toast = {
    id,
    type,
    title: options.title,
    message: options.message || "",
    icon: options.icon === null ? null : options.icon || getDefaultIcon(type),
    iconProps: options.iconProps,
    duration,
    showCloseButton: options.showCloseButton ?? DEFAULT_SHOW_CLOSE_BUTTON,
    progress: options.progress ?? (duration > 0 && duration !== Infinity && DEFAULT_PROGRESS),
    pauseOnHover: options.pauseOnHover ?? DEFAULT_PAUSE_ON_HOVER,
    actions: options.actions,
    customClass: options.customClass,
    allowHtml: options.allowHtml || false,
    onDismiss: options.onDismiss,
    createdAt: Date.now()
  };
  updateStore((toasts) => {
    const newToasts = [toast, ...toasts];
    if (newToasts.length > storeConfig.maxToasts) {
      return newToasts.slice(0, storeConfig.maxToasts);
    }
    return newToasts;
  });
  return id;
}
function error(message, options) {
  return show({ ...options, type: "error", message });
}
function dismiss(id) {
  let dismissedToast;
  updateStore((toasts) => {
    const index = toasts.findIndex((t) => t.id === id);
    if (index > -1) {
      dismissedToast = toasts[index];
      return [...toasts.slice(0, index), ...toasts.slice(index + 1)];
    }
    return toasts;
  });
  if (dismissedToast && dismissedToast.onDismiss) {
    dismissedToast.onDismiss(id);
  }
}
function _setMaxToasts(max) {
  if (max > 0) {
    storeConfig.maxToasts = max;
    trimToasts();
  }
}
export {
  Circle_x as C,
  _setMaxToasts as _,
  dismiss as d,
  error as e,
  toastStore as t
};
